import { useCallback, useMemo, useState } from "react";
import { putApi } from "../../../api";
import { PageLayout } from "../../../components/layout/PageLayout";
import { Button } from "../../../components/ui/Button";
import { DataTable } from "../../../components/ui/DataTable";
import { FilterBar } from "../../../components/ui/FilterBar";
import { DateCell } from "../../../components/ui/TableCells";
import { hasPermission, PERMISSIONS } from "../../../auth/permissions";
import { optionalString } from "../../../utils/propValidators";
import { useAuth } from "../../../context/AuthContext";
import { usePagedQuery } from "../../../hooks/usePagedQuery";
import { NoticeBar } from "../networkAccountUi";
import { SupplierTrackingLinkDrawer } from "./SupplierTrackingLinkDrawer";
import {
  QUEUE_STATE_OPTIONS,
  SUPPLIER_TRACKING_QUEUE_PATH,
  TRACKING_LINK_STATE,
  describeProvenance,
  describeState,
  stateTone,
  selectQueueRows,
  supplierTrackingLinkPath,
} from "./supplierTrackingLinkContract";

const PAGE_SIZE = 25;
const LOAD_ERROR = "The supplier tracking-link queue could not be loaded.";

// FilterBar always prepends an all-option with value "". fetchApi omits empty params, so choosing
// it sends no `state` at all — which the backend reads as "every state".
const FILTERS = [
  {
    key: "state",
    label: "Tracking link state",
    allLabel: "All states",
    options: QUEUE_STATE_OPTIONS,
  },
];

const TONE_CLASSES = {
  ok: "bg-emerald-50 text-emerald-700 border-emerald-200",
  warn: "bg-amber-50 text-amber-800 border-amber-200",
  bad: "bg-rose-50 text-rose-700 border-rose-200",
  muted: "bg-slate-50 text-slate-600 border-slate-200",
};

function StateBadge({ state }) {
  const tone = TONE_CLASSES[stateTone(state)] || TONE_CLASSES.muted;
  return (
    <span className={`inline-block whitespace-nowrap rounded border px-2 py-0.5 text-xs font-medium ${tone}`}>
      {describeState(state)}
    </span>
  );
}

StateBadge.propTypes = { state: optionalString };

/**
 * Network Operations → Supplier Tracking Links.
 *
 * A work queue of campaigns whose supplier tracking link must be generated by hand in the
 * supplier portal. Partnerize does not expose an API that creates or returns tracking links, so
 * this queue is the acquisition path.
 *
 * The full attributed tracking URL is never rendered: the backend returns its host only.
 */
export function SupplierTrackingLinksPage() {
  const { user } = useAuth();
  const canManage = hasPermission(user, PERMISSIONS.TRACKING_MANAGE);
  const [filters, setFilters] = useState({ state: TRACKING_LINK_STATE.NOT_GENERATED });
  const [active, setActive] = useState(null);
  const [saved, setSaved] = useState(null);

  const query = useMemo(() => ({ supplier: "PARTNERIZE", state: filters.state }), [filters.state]);
  // usePagedQuery exposes the envelope's `data` array as `rows`; it has no `data` key of its own.
  // Destructuring `data` here yielded undefined, so every successful 200 rendered as empty.
  const { rows: queueRows, pagination, loading, error, page, setPage, reload } = usePagedQuery(
    SUPPLIER_TRACKING_QUEUE_PATH,
    query,
    { pageSize: PAGE_SIZE, safeErrorMessage: LOAD_ERROR },
  );

  const rows = useMemo(() => selectQueueRows(queueRows), [queueRows]);

  const save = useCallback(
    async ({ id, supplierTrackingUrl, reason }) => {
      await putApi(supplierTrackingLinkPath(id), { supplierTrackingUrl, ...(reason ? { reason } : {}) });
      setActive(null);
      setSaved("Supplier tracking link saved.");
      await reload();
    },
    [reload],
  );

  const columns = useMemo(
    () => [
      {
        key: "campaignName",
        header: "Brand / Campaign",
        render: (row) => (
          <div className="min-w-0">
            <div className="truncate font-medium text-slate-800">{row.campaignName || "—"}</div>
            {row.brandName && <div className="truncate text-xs text-slate-500">{row.brandName}</div>}
          </div>
        ),
      },
      {
        key: "supplierCampaignId",
        header: "Supplier campaign ID",
        render: (row) => <span className="font-mono text-xs text-slate-600">{row.supplierCampaignId || "—"}</span>,
      },
      {
        key: "participationStatus",
        header: "Relationship",
        render: (row) => (
          <span className="text-xs text-slate-600">
            {row.participationStatus || (row.isJoined ? "JOINED" : "—")}
          </span>
        ),
      },
      {
        key: "campaignStatus",
        header: "Campaign status",
        render: (row) => <span className="text-xs text-slate-600">{row.campaignStatus || "—"}</span>,
      },
      {
        key: "state",
        header: "Supplier tracking link",
        render: (row) => (
          <div className="space-y-1">
            <StateBadge state={row.state} />
            {row.supplierTrackingUrlHost && (
              <div className="font-mono text-[11px] text-slate-500">{row.supplierTrackingUrlHost}</div>
            )}
          </div>
        ),
      },
      {
        key: "provenance",
        header: "Provenance",
        render: (row) => <span className="text-xs text-slate-600">{describeProvenance(row.provenance)}</span>,
      },
      {
        key: "updatedAt",
        header: "Last updated",
        render: (row) => <DateCell value={row.updatedAt} />,
      },
      {
        key: "action",
        header: "Action",
        render: (row) =>
          canManage ? (
            <Button size="sm" variant="secondary" onClick={() => setActive(row)}>
              {row.hasSupplierTrackingUrl ? "Replace link" : "Add supplier tracking link"}
            </Button>
          ) : (
            <span className="text-xs text-slate-400">Read only</span>
          ),
      },
    ],
    [canManage],
  );

  return (
    <PageLayout
      title="Supplier tracking links"
      subtitle="Campaigns whose supplier tracking link must be generated manually in the network portal."
    >
      <div className="space-y-4">
        <NoticeBar tone="info">
          Partnerize does not return a publisher tracking link when a campaign is joined or approved.
          Generate the link in the portal under <strong>Tracking → Create Tracking Link</strong>, then paste
          it here. A campaign with no link is still valid and assignable, but MBO client tracking links
          cannot be activated for it until a supplier link exists.
        </NoticeBar>

        {saved && <NoticeBar tone="info">{saved}</NoticeBar>}

        {/* FilterBar calls onChange(key, value), not onChange(nextFilters). */}
        <FilterBar
          filters={FILTERS}
          values={filters}
          onChange={(key, value) => setFilters((prev) => ({ ...prev, [key]: value }))}
        />

        <DataTable
          columns={columns}
          rows={rows}
          loading={loading}
          error={error}
          onRetry={reload}
          emptyTitle="Nothing to action"
          emptyDescription="No joined Partnerize campaigns are waiting for a supplier tracking link."
          page={page}
          total={pagination?.total ?? null}
          totalPages={pagination?.totalPages ?? null}
          pageSize={PAGE_SIZE}
          onPageChange={setPage}
        />
      </div>

      {active && (
        <SupplierTrackingLinkDrawer row={active} onClose={() => setActive(null)} onSave={save} />
      )}
    </PageLayout>
  );
}

export default SupplierTrackingLinksPage;
